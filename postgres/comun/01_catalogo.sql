-- =============================================================================
-- Catálogo compartido. Se crea idéntico en los tres nodos:
--   * pg-centro es el dueño de los datos (única copia que acepta escrituras).
--   * pg-norte y pg-sur reciben una copia por replicación lógica asíncrona,
--     lo que les permite validar y consultar sin depender del enlace central.
-- =============================================================================

CREATE TABLE sucursales (
    id        integer PRIMARY KEY,
    nombre    text NOT NULL,
    region    text NOT NULL CHECK (region IN ('norte', 'centro', 'sur')),
    provincia text NOT NULL,
    ciudad    text NOT NULL,
    lat       double precision NOT NULL,
    lon       double precision NOT NULL
);

CREATE TABLE vehiculos (
    id               integer PRIMARY KEY,
    patente          text NOT NULL UNIQUE,
    tipo             text NOT NULL CHECK (tipo IN ('utilitario', 'camion', 'camion_refrigerado')),
    capacidad_kg     integer NOT NULL CHECK (capacidad_kg > 0),
    sucursal_base_id integer NOT NULL REFERENCES sucursales (id)
);

-- Fragmento vertical "operativo" de Clientes: lo que una sucursal necesita
-- para despachar. El fragmento sensible vive solo en pg-centro.
CREATE TABLE clientes_operativo (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         text NOT NULL,
    email          text NOT NULL UNIQUE,
    telefono       text,
    direccion      text NOT NULL,
    ciudad         text NOT NULL,
    provincia      text NOT NULL,
    region         text NOT NULL CHECK (region IN ('norte', 'centro', 'sur')),
    activo         boolean NOT NULL DEFAULT true,
    actualizado_en timestamptz NOT NULL DEFAULT now()
);
